use serde::{Deserialize, Serialize};

/// Shared action/event discriminator; cmd vs evt is determined by which bus carries the message.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Kind {
    Play,
    Pause,
    TogglePlay,
    Seek,
    SetVolume,
    SetEq,
    SetEqBand,
    SetSpeed,
    SetTempoRange,
    SetKeyLock,
    SetKeyShift,
    SetKeyboardRoot,
    SetKeyboardPage,
    SetKeyShiftPage,
    SetFilter,
    SetGainTrim,
    /// FX unit (shared, mixer-scoped) slot effect selection.
    SetFxUnitSlot,
    /// FX unit slot on/off.
    SetFxUnitSlotEnabled,
    /// FX unit slot wet/dry.
    SetFxUnitWet,
    /// FX unit slot knob.
    SetFxUnitParam,
    /// Route this deck's pre-fader signal through the FX unit (deck-scoped).
    SetDeckFxRouted,
    SetHeadphoneCue,
    ToggleHeadphoneCue,
    SetCrossfader,
    SetMasterVolume,
    SetCueVolume,
    SetCueMix,
    SetMasterCue,
    ToggleMasterCue,
    ToggleSync,
    SetMasterDeck,
    Unload,
    SetCuePoint,
    BeginCueHold,
    EndCueHold,
    SetQuantize,
    ToggleQuantize,
    SetSlip,
    ToggleSlip,
    SetAutoLoop,
    LoopIn,
    LoopOut,
    ExitLoop,
    BeatJump,
    SetPadMode,
    BeginLoopRoll,
    EndLoopRoll,
    /// Generic pad: engine `pad_mode` selects the named pair (notes do not change per mode).
    PadPress,
    PadRelease,
    /// Hardware note banks that already encode mode (Pioneer).
    HotCuePadPress,
    HotCuePadRelease,
    LoopRollPadPress,
    LoopRollPadRelease,
    BeatJumpPadPress,
    BeatJumpPadRelease,
    SamplerPadPress,
    SamplerPadRelease,
    KeyboardPadPress,
    KeyboardPadRelease,
    KeyShiftPadPress,
    KeyShiftPadRelease,
    TriggerHotCue,
    RecallSavedLoop,
    AssignSampler,
    AssignSamplerTrack,
    ClearSampler,
    SetSamplerBank,
    CreateSamplerBank,
    UpdateSamplerBank,
    DeleteSamplerBank,
    SaveHotCue,
    DeleteHotCue,
    SaveLoop,
    DeleteLoop,
    LoadPath,
    LoadLibraryTrack,
    JogTouch,
    JogTurn,
    SetJogMode,
    StartEngine,
    Updated,
    Position,
    Levels,
    Status,
    Error,
    Notice,
}
